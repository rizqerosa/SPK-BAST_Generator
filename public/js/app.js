async function initForm() {
  if (!document.getElementById("form-spk-bast")) return;

  setLoading(true);
  try {
    // Fetch semua master data secara paralel
    const [pegawaiData, mitraData, kegiatanData, spkBastData, bastSmPpkData] = await Promise.all([
      getPegawai(),
      getMitra(),
      getKegiatan(),
      getSpkBast(),
      getBastSmPpk(),
    ]);

    AppState.pegawai   = pegawaiData;
    AppState.mitra     = mitraData;
    AppState.kegiatan  = kegiatanData;
    AppState.spkBast   = spkBastData;
    AppState.bastSmPpk = bastSmPpkData;

    populatePetugasDropdown();
    populatePegawaiDropdowns();
    populateKegiatanOptions();

    // Auto-generate nomor SPK & BAST awal
    const yrInput = document.getElementById("input-tahun");
    const currentYr = parseInt(yrInput?.value) || new Date().getFullYear();
    autoGenerateDocNumbers(currentYr);

    // 1. Date picker Tanggal SPK (single date) -> Auto-extract Bulan, Tahun & Nomor SPK/BAST
    const tglSpkInput = document.getElementById("input-tanggal-spk");
    if (tglSpkInput) {
      tglSpkInput.addEventListener("change", function() {
        if (!this.value) return;
        const d = new Date(this.value);
        if (isNaN(d.getTime())) return;
        const months = ["Januari","Februari","Maret","April","Mei","Juni","Juli","Agustus","September","Oktober","November","Desember"];
        const selBulan = document.getElementById("input-bulan");
        const inputTahun = document.getElementById("input-tahun");
        const yr = d.getFullYear();
        if (selBulan) selBulan.value = months[d.getMonth()];
        if (inputTahun) inputTahun.value = yr;

        autoGenerateDocNumbers(yr);
      });
    }

    if (yrInput) {
      yrInput.addEventListener("change", function() {
        const yr = parseInt(this.value) || new Date().getFullYear();
        autoGenerateDocNumbers(yr);
      });
    }

    // Listener validasi duplikasi nomor SPK & BAST saat diedit
    const docNumInputIds = [
      "input-no-spk",
      "input-no-bast-ppl-pml",
      "input-no-bast-ppl-sm",
      "input-no-bast-pml-sm",
      "input-no-bast-sm-ppk"
    ];
    docNumInputIds.forEach(id => {
      const el = document.getElementById(id);
      if (el) {
        el.addEventListener("input", function() {
          validateDocNumberInput(this, false);
          validateAllDocNumberInputs();
        });
        el.addEventListener("change", function() {
          validateDocNumberInput(this, true);
          validateAllDocNumberInputs();
        });
      }
    });

    // 2. Radio Sumber Petugas (Mitra vs Pegawai)
    document.querySelectorAll('input[name="sumber_petugas"]').forEach(r => {
      r.addEventListener("change", () => {
        clearSelectedPetugas();
      });
    });

    // 3. Peran Petugas (PPL vs PML)
    const selPeran = document.getElementById("sel-peran-petugas");
    if (selPeran) {
      selPeran.addEventListener("change", togglePeranFields);
      togglePeranFields();
    }

    // 4. Jenis Bundling (spk_bast vs sm_ppk)
    document.querySelectorAll('input[name="target_doc_type"]').forEach(r => {
      r.addEventListener("change", toggleBundlingFields);
    });
    toggleBundlingFields();

    // Event handlers
    document.getElementById("btn-tambah-kegiatan").addEventListener("click", tambahDetailRow);
    document.getElementById("form-spk-bast").addEventListener("submit", handleFormSubmit);
    document.getElementById("detail-tbody").addEventListener("input", updateTotalHonor);

  } catch (err) {
    showToast("Gagal memuat data master dari Sheets: " + err.message, "danger", 6000);
    console.error(err);
  } finally {
    setLoading(false);
  }
}

function togglePeranFields() {
  const peran = document.getElementById("sel-peran-petugas")?.value || "ppl";
  const grpPml = document.getElementById("grp-pml");
  const grpBastPpl = document.getElementById("grp-bast-ppl");
  const grpBastPml = document.getElementById("grp-bast-pml");

  if (peran === "ppl") {
    if (grpPml) grpPml.style.display = "";
    if (grpBastPpl) grpBastPpl.style.display = "";
    if (grpBastPml) grpBastPml.style.display = "none";
  } else if (peran === "pml") {
    if (grpPml) grpPml.style.display = "none";
    if (grpBastPpl) grpBastPpl.style.display = "none";
    if (grpBastPml) grpBastPml.style.display = "";
  }
  validateAllDocNumberInputs();
}

function toggleBundlingFields() {
  const docType = document.querySelector('input[name="target_doc_type"]:checked')?.value || "spk_bast";
  const cardPetugas  = document.getElementById("card-petugas");
  const cardPeran    = document.getElementById("card-peran");
  const grpBastSmPpk = document.getElementById("grp-bast-sm-ppk");

  if (docType === "sm_ppk") {
    if (cardPetugas)  cardPetugas.style.display = "none";
    if (cardPeran)    cardPeran.style.display   = "none";
    if (grpBastSmPpk) grpBastSmPpk.style.display = "";
  } else {
    if (cardPetugas)  cardPetugas.style.display = "";
    if (cardPeran)    cardPeran.style.display   = "";
    if (grpBastSmPpk) grpBastSmPpk.style.display = "none";
  }
  validateAllDocNumberInputs();
}

let currentPetugasPage = 1;
const PETUGAS_PER_PAGE = 10;

function populatePetugasDropdown() {
  renderPetugasTable();
}

function renderPetugasTable() {
  const sel = document.getElementById("sel-mitra");
  const tbody = document.getElementById("tbody-petugas-list");
  if (!sel || !tbody) return;

  const previousVal   = sel.value;
  const sumber        = document.querySelector('input[name="sumber_petugas"]:checked')?.value || "mitra";
  const searchInput   = document.getElementById("search-mitra");
  const filterAsalSel = document.getElementById("filter-asal-mitra");
  const labelEl       = document.getElementById("label-sel-mitra");

  const isMitra = (sumber === "mitra");
  if (labelEl) {
    labelEl.innerHTML = isMitra
      ? `Pilih Mitra Lapangan <span class="required">*</span>`
      : `Pilih Pegawai BPS <span class="required">*</span>`;
  }
  if (filterAsalSel) filterAsalSel.style.display = isMitra ? "" : "none";

  // Rebuild opsi kecamatan dari data mitra
  if (isMitra && filterAsalSel) {
    const prevAsal = filterAsalSel.value;
    const asalSet  = new Set();
    (AppState.mitra || []).forEach(m => {
      const raw  = getMitraAsal(m);
      if (!raw || raw === "-") return;
      const norm = raw.trim().replace(/\w\S*/g, w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase());
      asalSet.add(norm);
    });

    filterAsalSel.innerHTML = `<option value="">Semua Kecamatan</option>`;
    Array.from(asalSet).sort().forEach(asal => {
      const opt = document.createElement("option");
      opt.value = asal;
      opt.textContent = asal;
      filterAsalSel.appendChild(opt);
    });

    if (prevAsal && asalSet.has(prevAsal)) {
      filterAsalSel.value = prevAsal;
    }
  }

  const query        = (searchInput?.value || "").toLowerCase().trim();
  const selectedAsal = filterAsalSel?.value || "";
  const rawList      = isMitra ? (AppState.mitra || []) : (AppState.pegawai || []);

  let filtered = rawList.filter(item => {
    const name = isMitra ? getMitraName(item) : getPegawaiName(item);
    if (!name) return false;

    if (isMitra) {
      const id      = getMitraId(item);
      const asal    = getMitraAsal(item);
      const nik     = String(item.NIK || item.nik || "");
      const sobatId = String(item.Sobat_ID || item["Sobat ID"] || "");

      if (selectedAsal) {
        const normalizedAsal = asal.trim().replace(/\w\S*/g, w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase());
        if (normalizedAsal !== selectedAsal) return false;
      }
      if (query) {
        return name.toLowerCase().includes(query) ||
               id.toLowerCase().includes(query) ||
               nik.toLowerCase().includes(query) ||
               sobatId.toLowerCase().includes(query) ||
               asal.toLowerCase().includes(query);
      }
    } else {
      const nip = getPegawaiNip(item);
      const jab = String(item.Jabatan || "");
      if (query) {
        return name.toLowerCase().includes(query) ||
               nip.toLowerCase().includes(query) ||
               jab.toLowerCase().includes(query);
      }
    }
    return true;
  });

  // Urutkan A-Z berdasarkan Nama
  filtered.sort((a, b) => {
    const nameA = isMitra ? getMitraName(a) : getPegawaiName(a);
    const nameB = isMitra ? getMitraName(b) : getPegawaiName(b);
    return nameA.localeCompare(nameB, "id", { sensitivity: "base" });
  });

  // Re-populate hidden <select id="sel-mitra"> untuk form submit validation
  sel.innerHTML = `<option value="">-- Pilih ${isMitra ? "Mitra Lapangan" : "Pegawai BPS"} --</option>`;
  let foundPrevious = false;
  filtered.forEach(item => {
    const id   = isMitra ? getMitraId(item) : getPegawaiNip(item);
    const name = isMitra ? getMitraName(item) : getPegawaiName(item);
    const meta = isMitra ? `${getMitraPosisi(item)} (${getMitraAsal(item)})` : `${item.Jabatan || "Pegawai BPS"} (NIP: ${id})`;

    const opt = document.createElement("option");
    opt.value = id;
    opt.textContent = `${name} — ${meta}`;
    if (id && id === previousVal) {
      opt.selected = true;
      foundPrevious = true;
    }
    sel.appendChild(opt);
  });

  if (previousVal && !foundPrevious) {
    const currentName = document.getElementById("selected-petugas-name")?.textContent || previousVal;
    const currentMeta = document.getElementById("selected-petugas-meta")?.textContent || "";
    const opt = document.createElement("option");
    opt.value = previousVal;
    opt.textContent = `${currentName} — ${currentMeta}`;
    opt.selected = true;
    sel.appendChild(opt);
  }

  // Hitung Pagination
  const totalItems = filtered.length;
  const totalPages = Math.ceil(totalItems / PETUGAS_PER_PAGE) || 1;
  if (currentPetugasPage > totalPages) currentPetugasPage = totalPages;
  if (currentPetugasPage < 1) currentPetugasPage = 1;

  const startIndex = (currentPetugasPage - 1) * PETUGAS_PER_PAGE;
  const pageItems  = filtered.slice(startIndex, startIndex + PETUGAS_PER_PAGE);

  // Render Baris Tabel
  if (pageItems.length === 0) {
    tbody.innerHTML = `<tr><td colspan="3" style="text-align:center; padding: 24px; color: var(--gray-500);">Data tidak ditemukan.</td></tr>`;
  } else {
    tbody.innerHTML = pageItems.map((item, index) => {
      const rowNo = startIndex + index + 1;
      const id    = isMitra ? getMitraId(item) : getPegawaiNip(item);
      const name  = isMitra ? getMitraName(item) : getPegawaiName(item);
      const meta  = isMitra
        ? `${getMitraPosisi(item)} · Kec. ${getMitraAsal(item)} · NIK: ${item.NIK || id}`
        : `${item.Jabatan || "Pegawai BPS"} · NIP: ${id}`;
      const isChecked = (sel.value === id);

      const safeId   = escapeHtml(id);
      const safeName = escapeHtml(name);
      const safeMeta = escapeHtml(meta);

      return `
        <tr class="${isChecked ? 'selected-row' : ''}" style="cursor:pointer;" onclick="selectPetugasFromTable('${safeId}', '${safeName}', '${safeMeta}')">
          <td style="text-align: center; font-weight: 600;">${rowNo}</td>
          <td style="padding-left: 12px;">
            <div style="font-weight: 600; color: var(--gray-900); font-size: 0.88rem;">${safeName}</div>
            <div style="font-size: 0.76rem; color: var(--gray-500);">${safeMeta}</div>
          </td>
          <td style="text-align: center;">
            <input type="radio" name="petugas_radio_choice" value="${safeId}" ${isChecked ? 'checked' : ''}
                   onclick="event.stopPropagation(); selectPetugasFromTable('${safeId}', '${safeName}', '${safeMeta}')">
          </td>
        </tr>`;
    }).join("");
  }

  // Update Kontrol Pagination
  const infoEl    = document.getElementById("pagination-info");
  const pageNumEl = document.getElementById("pagination-page-num");
  const btnPrev   = document.getElementById("btn-prev-page");
  const btnNext   = document.getElementById("btn-next-page");

  if (infoEl) {
    infoEl.textContent = totalItems > 0
      ? `Menampilkan ${startIndex + 1} - ${Math.min(startIndex + PETUGAS_PER_PAGE, totalItems)} dari ${totalItems} data`
      : `Menampilkan 0 - 0 dari 0 data`;
  }
  if (pageNumEl) {
    pageNumEl.textContent = `Halaman ${currentPetugasPage} / ${totalPages}`;
  }
  if (btnPrev) btnPrev.disabled = (currentPetugasPage <= 1);
  if (btnNext) btnNext.disabled = (currentPetugasPage >= totalPages);

  // Bind Listener Input & Filter
  if (searchInput && !searchInput.dataset.boundTable) {
    searchInput.dataset.boundTable = "true";
    searchInput.addEventListener("input", () => {
      currentPetugasPage = 1;
      renderPetugasTable();
    });
  }

  if (filterAsalSel && !filterAsalSel.dataset.boundTable) {
    filterAsalSel.dataset.boundTable = "true";
    filterAsalSel.addEventListener("change", () => {
      currentPetugasPage = 1;
      renderPetugasTable();
    });
  }

  if (btnPrev && !btnPrev.dataset.bound) {
    btnPrev.dataset.bound = "true";
    btnPrev.addEventListener("click", () => {
      if (currentPetugasPage > 1) {
        currentPetugasPage--;
        renderPetugasTable();
      }
    });
  }

  if (btnNext && !btnNext.dataset.bound) {
    btnNext.dataset.bound = "true";
    btnNext.addEventListener("click", () => {
      if (currentPetugasPage < totalPages) {
        currentPetugasPage++;
        renderPetugasTable();
      }
    });
  }

  updateSelectedPetugasCard();
}

function selectPetugasFromTable(id, name, meta) {
  const sel = document.getElementById("sel-mitra");
  if (sel) {
    let opt = Array.from(sel.options).find(o => o.value === id);
    if (!opt) {
      opt = document.createElement("option");
      opt.value = id;
      opt.textContent = `${name} — ${meta}`;
      sel.appendChild(opt);
    }
    sel.value = id;
  }

  updateSelectedPetugasCard(name, meta);
  renderPetugasTable();
}

function updateSelectedPetugasCard(optName, optMeta) {
  const sel = document.getElementById("sel-mitra");
  const card = document.getElementById("selected-petugas-card");
  const elName = document.getElementById("selected-petugas-name");
  const elMeta = document.getElementById("selected-petugas-meta");
  if (!sel || !card) return;

  const val = sel.value;
  if (!val) {
    card.style.display = "none";
    return;
  }

  if (optName && optMeta) {
    if (elName) elName.textContent = optName;
    if (elMeta) elMeta.textContent = optMeta;
    card.style.display = "flex";
    return;
  }

  const selectedOpt = sel.options[sel.selectedIndex];
  if (selectedOpt && selectedOpt.value) {
    const text = selectedOpt.textContent || "";
    const parts = text.split(" — ");
    if (elName) elName.textContent = parts[0] || text;
    if (elMeta) elMeta.textContent = parts[1] || "";
    card.style.display = "flex";
  } else {
    card.style.display = "none";
  }
}

function clearSelectedPetugas() {
  const sel = document.getElementById("sel-mitra");
  if (sel) sel.value = "";
  const searchInput = document.getElementById("search-mitra");
  if (searchInput) searchInput.value = "";
  updateSelectedPetugasCard();
  if (searchInput) searchInput.focus();
}

function autoGenerateDocNumbers(inputTahunVal) {
  const yr = parseInt(inputTahunVal) || parseInt(document.getElementById("input-tahun")?.value) || new Date().getFullYear();

  const spkRecords = AppState.spkBast || [];
  const smPpkRecords = AppState.bastSmPpk || [];

  // Hitung nomor SPK terbesar untuk tahun yr
  let maxSpkNo = 0;
  spkRecords.forEach(r => {
    const recordYear = parseInt(r.Tahun || r.tahun || r["Tahun"] || (r["Tanggal SPK"] || r.Tanggal_SPK || "").slice(0, 4)) || yr;
    const spkVal = r.No_SPK || r.Nomor_SPK || r["No_SPK"] || r["Nomor_SPK"] || r["No SPK"] || r["Nomor SPK"] || "";
    
    if (recordYear === yr && spkVal) {
      const matches = String(spkVal).match(/\d+/g);
      if (matches) {
        matches.forEach(numStr => {
          const val = parseInt(numStr, 10);
          if (val > maxSpkNo && val < 2000) maxSpkNo = val;
        });
      }
    }
  });

  // Hitung nomor BAST terbesar untuk tahun yr
  let maxBastNo = 0;
  const allBastRecords = [...spkRecords, ...smPpkRecords];
  allBastRecords.forEach(r => {
    const recordYear = parseInt(r.Tahun || r.tahun || r["Tahun"] || "") || yr;
    if (recordYear === yr) {
      const bastFields = [
        r.No_BAST_PPL_PML, r["No_BAST_PPL_PML"], r["No BAST PPL PML"],
        r.No_BAST_PPL_SM,  r["No_BAST_PPL_SM"],  r["No BAST PPL SM"],
        r.No_BAST_PML_SM,  r["No_BAST_PML_SM"],  r["No BAST PML SM"],
        r.No_BAST_SM_PPK,  r["No_BAST_SM_PPK"],  r["No BAST SM PPK"]
      ];
      bastFields.forEach(bVal => {
        if (bVal) {
          const m = String(bVal).match(/^(\d+)\//);
          if (m) {
            const val = parseInt(m[1], 10);
            if (val > maxBastNo) maxBastNo = val;
          } else {
            const digits = String(bVal).match(/\d+/g);
            if (digits) {
              digits.forEach(dStr => {
                const val = parseInt(dStr, 10);
                if (val > maxBastNo && val < 2000) maxBastNo = val;
              });
            }
          }
        }
      });
    }
  });

  const nextSpk = maxSpkNo + 1;
  let bastSeq = maxBastNo + 1;
  const formatBastStr = (seq, year) => String(seq).padStart(3, "0") + `/BPS/1172/BAST/${year}`;

  const inputNoSpk = document.getElementById("input-no-spk");
  if (inputNoSpk) {
    inputNoSpk.value = `Nomor ${nextSpk} Tahun ${yr}`;
  }

  const bastPplPml = document.getElementById("input-no-bast-ppl-pml");
  if (bastPplPml) bastPplPml.value = formatBastStr(bastSeq++, yr);

  const bastPplSm = document.getElementById("input-no-bast-ppl-sm");
  if (bastPplSm) bastPplSm.value = formatBastStr(bastSeq++, yr);

  const bastPmlSm = document.getElementById("input-no-bast-pml-sm");
  if (bastPmlSm) bastPmlSm.value = formatBastStr(bastSeq++, yr);

  const bastSmPpk = document.getElementById("input-no-bast-sm-ppk");
  if (bastSmPpk) bastSmPpk.value = formatBastStr(bastSeq++, yr);

  validateAllDocNumberInputs();
}

// ─── Validasi Duplikasi Nomor SPK & BAST ─────────────────────
function checkDuplicateDocNumber(val, currentInputId) {
  if (!val) return null;
  const target = val.trim().toLowerCase();

  const currentDocId = AppState.currentDocId;
  const spkRecords = AppState.spkBast || [];
  const smPpkRecords = AppState.bastSmPpk || [];

  const spkFields = ["No_SPK", "Nomor_SPK", "No SPK", "Nomor SPK"];
  const bastFields = [
    "No_BAST_PPL_PML", "No_BAST_PPL_SM", "No_BAST_PML_SM", "No_BAST_SM_PPK",
    "No BAST PPL PML", "No BAST PPL SM", "No BAST PML SM", "No BAST SM PPK",
    "Nomor_BAST_PPL_PML", "Nomor_BAST_PPL_SM", "Nomor_BAST_PML_SM", "Nomor_BAST_SM_PPK"
  ];

  // 1. Cek terhadap database Sheets (spkBast)
  for (const r of spkRecords) {
    if (currentDocId && String(r.ID_Dokumen) === String(currentDocId)) continue;
    for (const f of [...spkFields, ...bastFields]) {
      const v = r[f];
      if (v && String(v).trim().toLowerCase() === target) {
        return {
          source: "Sheets",
          label: r.Judul_Pekerjaan_Dokumen || r.No_SPK || r.ID_Dokumen || "Dokumen Database",
          record: r
        };
      }
    }
  }

  // 2. Cek terhadap database Sheets (bastSmPpk)
  for (const r of smPpkRecords) {
    if (currentDocId && String(r.ID_Dokumen) === String(currentDocId)) continue;
    for (const f of bastFields) {
      const v = r[f];
      if (v && String(v).trim().toLowerCase() === target) {
        return {
          source: "Sheets",
          label: r.Judul_Pekerjaan_Dokumen || r.No_BAST_SM_PPK || r.ID_Dokumen || "Dokumen SM-PPK",
          record: r
        };
      }
    }
  }

  // 3. Cek terhadap input lain pada form yang sedang diisi
  const docNumInputIds = [
    "input-no-spk",
    "input-no-bast-ppl-pml",
    "input-no-bast-ppl-sm",
    "input-no-bast-pml-sm",
    "input-no-bast-sm-ppk"
  ];

  for (const otherId of docNumInputIds) {
    if (otherId === currentInputId) continue;
    const otherEl = document.getElementById(otherId);
    if (!otherEl) continue;

    // Pastikan elemen grup BAST-nya sedang tidak tersembunyi
    const formCardOrGrp = otherEl.closest("#grp-bast-ppl, #grp-bast-pml, #grp-bast-sm-ppk, .form-card");
    if (formCardOrGrp && window.getComputedStyle(formCardOrGrp).display === "none") continue;

    if (otherEl.value && otherEl.value.trim().toLowerCase() === target) {
      return {
        source: "Form",
        fieldId: otherId
      };
    }
  }

  return null;
}

// ─── Extraction Helper for Doc Numbers ───────────────────────
function extractSeqAndYearFromStr(val, defaultYear, isSpk = false) {
  if (!val) return null;
  const str = String(val).trim();
  if (!str) return null;

  let year = parseInt(defaultYear) || new Date().getFullYear();
  let seq = null;

  if (isSpk) {
    const yrMatch = str.match(/(?:Tahun|\/|\b)(20\d{2})\b/i);
    if (yrMatch) {
      year = parseInt(yrMatch[1], 10);
    }
    const matches = str.match(/\d+/g);
    if (matches) {
      for (const m of matches) {
        const num = parseInt(m, 10);
        if (num !== year && num > 0 && num < 2000) {
          seq = num;
          break;
        }
      }
    }
  } else {
    const yrMatch = str.match(/\/BAST\/(20\d{2})\b/i) || str.match(/(?:Tahun|\/|\b)(20\d{2})\b/i);
    if (yrMatch) {
      year = parseInt(yrMatch[1], 10);
    }
    const headMatch = str.match(/^(\d+)\//);
    if (headMatch) {
      seq = parseInt(headMatch[1], 10);
    } else {
      const matches = str.match(/\d+/g);
      if (matches) {
        for (const m of matches) {
          const num = parseInt(m, 10);
          if (num !== year && num > 0 && num < 2000) {
            seq = num;
            break;
          }
        }
      }
    }
  }

  if (seq === null || isNaN(seq) || seq <= 0) return null;
  return { seq, year };
}

// ─── Validasi Lompatan (Gap) Nomor SPK & BAST ────────────────
function checkGapDocNumber(val, currentInputId) {
  if (!val) return null;

  const defaultYear = parseInt(document.getElementById("input-tahun")?.value) || new Date().getFullYear();
  const isSpk = (currentInputId === "input-no-spk");

  const parsed = extractSeqAndYearFromStr(val, defaultYear, isSpk);
  if (!parsed) return null;

  const { seq: currentSeq, year: targetYear } = parsed;
  if (currentSeq <= 1) return null;

  const currentDocId = AppState.currentDocId;
  const spkRecords = AppState.spkBast || [];
  const smPpkRecords = AppState.bastSmPpk || [];

  const usedSeqs = new Set();

  if (isSpk) {
    spkRecords.forEach(r => {
      if (currentDocId && String(r.ID_Dokumen) === String(currentDocId)) return;
      const recYear = parseInt(r.Tahun || r.tahun || r["Tahun"] || (r["Tanggal SPK"] || r.Tanggal_SPK || "").slice(0, 4)) || defaultYear;
      if (recYear === targetYear) {
        const spkVal = r.No_SPK || r.Nomor_SPK || r["No_SPK"] || r["Nomor_SPK"] || r["No SPK"] || r["Nomor SPK"] || "";
        const p = extractSeqAndYearFromStr(spkVal, recYear, true);
        if (p && p.seq) usedSeqs.add(p.seq);
      }
    });
  } else {
    const allBastRecords = [...spkRecords, ...smPpkRecords];
    allBastRecords.forEach(r => {
      if (currentDocId && String(r.ID_Dokumen) === String(currentDocId)) return;
      const recYear = parseInt(r.Tahun || r.tahun || r["Tahun"] || "") || defaultYear;
      if (recYear === targetYear) {
        const bastFields = [
          r.No_BAST_PPL_PML, r["No_BAST_PPL_PML"], r["No BAST PPL PML"],
          r.No_BAST_PPL_SM,  r["No_BAST_PPL_SM"],  r["No BAST PPL SM"],
          r.No_BAST_PML_SM,  r["No_BAST_PML_SM"],  r["No BAST PML SM"],
          r.No_BAST_SM_PPK,  r["No_BAST_SM_PPK"],  r["No BAST SM PPK"],
          r.Nomor_BAST_PPL_PML, r.Nomor_BAST_PPL_SM, r.Nomor_BAST_PML_SM, r.Nomor_BAST_SM_PPK
        ];
        bastFields.forEach(bVal => {
          if (bVal) {
            const p = extractSeqAndYearFromStr(bVal, recYear, false);
            if (p && p.seq) usedSeqs.add(p.seq);
          }
        });
      }
    });

    const bastInputIds = [
      "input-no-bast-ppl-pml",
      "input-no-bast-ppl-sm",
      "input-no-bast-pml-sm",
      "input-no-bast-sm-ppk"
    ];
    bastInputIds.forEach(otherId => {
      if (otherId === currentInputId) return;
      const otherEl = document.getElementById(otherId);
      if (!otherEl || !otherEl.value) return;

      const formCardOrGrp = otherEl.closest("#grp-bast-ppl, #grp-bast-pml, #grp-bast-sm-ppk, .form-card");
      if (formCardOrGrp && window.getComputedStyle(formCardOrGrp).display === "none") return;

      const p = extractSeqAndYearFromStr(otherEl.value, targetYear, false);
      if (p && p.year === targetYear && p.seq) {
        usedSeqs.add(p.seq);
      }
    });
  }

  const missingNums = [];
  for (let i = 1; i < currentSeq; i++) {
    if (!usedSeqs.has(i)) {
      missingNums.push(i);
    }
  }

  if (missingNums.length > 0) {
    return {
      currentSeq,
      year: targetYear,
      missingNums
    };
  }

  return null;
}

function validateDocNumberInput(inputEl, triggerToast = false) {
  if (!inputEl) return { isDuplicate: false, hasGap: false };
  const val = inputEl.value ? inputEl.value.trim() : "";
  const inputId = inputEl.id;

  let warnEl = inputEl.parentNode.querySelector(".doc-num-warning-msg");

  if (!val) {
    inputEl.classList.remove("is-duplicate", "is-gap-warning");
    if (warnEl) warnEl.remove();
    return { isDuplicate: false, hasGap: false };
  }

  // 1. Cek duplikasi lebih dulu (Prioritas Tinggi - Merah)
  const dupInfo = checkDuplicateDocNumber(val, inputId);

  if (dupInfo) {
    inputEl.classList.remove("is-gap-warning");
    inputEl.classList.add("is-duplicate");

    let textMsg = "⚠️ Nomor ini sudah dipakai";
    if (dupInfo.source === "Sheets") {
      textMsg += ` pada database (${dupInfo.label})`;
    } else if (dupInfo.source === "Form") {
      textMsg += ` pada input lain di form ini`;
    }

    if (!warnEl) {
      warnEl = document.createElement("div");
      warnEl.className = "doc-num-warning-msg danger";
      inputEl.parentNode.appendChild(warnEl);
    } else {
      warnEl.className = "doc-num-warning-msg danger";
    }
    warnEl.innerHTML = textMsg;

    if (triggerToast) {
      showToast(`⚠️ Peringatan: Nomor "${val}" sudah dipakai (${dupInfo.source === "Form" ? "Form" : dupInfo.label})!`, "warning", 4000);
    }
    return { isDuplicate: true, hasGap: false };
  }

  // 2. Cek nomor melompati urutan (Gap Warning - Kuning)
  const gapInfo = checkGapDocNumber(val, inputId);
  if (gapInfo) {
    inputEl.classList.remove("is-duplicate");
    inputEl.classList.add("is-gap-warning");

    const missingStr = gapInfo.missingNums.join(", ");
    const labelNomor = gapInfo.missingNums.length > 1 ? "Nomor-nomor" : "Nomor";
    const textMsg = `⚠️ Peringatan: ${labelNomor} ${missingStr} belum ada untuk tahun ${gapInfo.year} (melompati urutan)`;

    if (!warnEl) {
      warnEl = document.createElement("div");
      warnEl.className = "doc-num-warning-msg warning";
      inputEl.parentNode.appendChild(warnEl);
    } else {
      warnEl.className = "doc-num-warning-msg warning";
    }
    warnEl.innerHTML = textMsg;

    if (triggerToast) {
      showToast(textMsg, "warning", 4000);
    }
    return { isDuplicate: false, hasGap: true };
  }

  inputEl.classList.remove("is-duplicate", "is-gap-warning");
  if (warnEl) warnEl.remove();
  return { isDuplicate: false, hasGap: false };
}

function validateAllDocNumberInputs() {
  const docNumInputIds = [
    "input-no-spk",
    "input-no-bast-ppl-pml",
    "input-no-bast-ppl-sm",
    "input-no-bast-pml-sm",
    "input-no-bast-sm-ppk"
  ];

  let hasDuplicate = false;
  let hasGap = false;

  docNumInputIds.forEach(id => {
    const el = document.getElementById(id);
    if (el) {
      const parentGrp = el.closest("#grp-bast-ppl, #grp-bast-pml, #grp-bast-sm-ppk, .form-card");
      if (parentGrp && window.getComputedStyle(parentGrp).display === "none") {
        el.classList.remove("is-duplicate", "is-gap-warning");
        const warnEl = el.parentNode.querySelector(".doc-num-warning-msg");
        if (warnEl) warnEl.remove();
        return;
      }
      const res = validateDocNumberInput(el, false);
      if (res.isDuplicate) hasDuplicate = true;
      if (res.hasGap) hasGap = true;
    }
  });

  return { hasDuplicate, hasGap };
}

