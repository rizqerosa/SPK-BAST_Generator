/* ─── Searchable Select UI Component ────────────────────────── */
function initSearchableSelect(selectId) {
  const sel = document.getElementById(selectId);
  if (!sel) return;

  let wrapper = sel.closest(".ss-wrapper");
  if (!wrapper) {
    wrapper = document.createElement("div");
    wrapper.className = "ss-wrapper";
    sel.parentNode.insertBefore(wrapper, sel);
    wrapper.appendChild(sel);
    sel.style.display = "none";
  } else {
    const oldTrig = wrapper.querySelector(".ss-trigger");
    const oldDrop = wrapper.querySelector(".ss-dropdown");
    if (oldTrig) oldTrig.remove();
    if (oldDrop) oldDrop.remove();
  }

  const trigger = document.createElement("div");
  trigger.className = "ss-trigger";
  trigger.tabIndex = 0;
  trigger.innerHTML = `<span class="ss-selected-text"></span><span class="ss-arrow">▼</span>`;

  const dropdown = document.createElement("div");
  dropdown.className = "ss-dropdown";
  dropdown.innerHTML = `
    <div class="ss-search-wrap">
      <span class="ss-search-icon">🔍</span>
      <input type="text" class="ss-search-input" placeholder="Cari nama atau opsi..." autocomplete="off">
    </div>
    <div class="ss-options-list"></div>
  `;

  wrapper.appendChild(trigger);
  wrapper.appendChild(dropdown);

  const textSpan = trigger.querySelector(".ss-selected-text");
  const searchInput = dropdown.querySelector(".ss-search-input");
  const optionsList = dropdown.querySelector(".ss-options-list");

  function buildOptionsUI() {
    optionsList.innerHTML = "";
    const query = (searchInput.value || "").toLowerCase().trim();
    let count = 0;

    Array.from(sel.children).forEach(child => {
      if (child.tagName === "OPTGROUP") {
        const groupLabel = child.label;
        const opts = Array.from(child.children).filter(opt => {
          if (!opt.value) return false;
          if (!query) return true;
          return opt.textContent.toLowerCase().includes(query) || opt.value.toLowerCase().includes(query);
        });

        if (opts.length > 0) {
          const lbl = document.createElement("div");
          lbl.className = "ss-optgroup-label";
          lbl.textContent = groupLabel;
          optionsList.appendChild(lbl);

          opts.forEach(opt => {
            count++;
            const div = document.createElement("div");
            div.className = `ss-option ${sel.value === opt.value ? 'selected' : ''}`;
            div.textContent = opt.textContent;
            div.dataset.value = opt.value;
            div.addEventListener("click", () => {
              sel.value = opt.value;
              sel.dispatchEvent(new Event("change"));
              updateTriggerText();
              closeDropdown();
            });
            optionsList.appendChild(div);
          });
        }
      } else if (child.tagName === "OPTION") {
        const isPlaceholder = !child.value;
        if (isPlaceholder && query) return;
        if (!query || child.textContent.toLowerCase().includes(query) || child.value.toLowerCase().includes(query)) {
          count++;
          const div = document.createElement("div");
          div.className = `ss-option ${sel.value === child.value ? 'selected' : ''}`;
          div.textContent = child.textContent;
          div.dataset.value = child.value;
          div.addEventListener("click", () => {
            sel.value = child.value;
            sel.dispatchEvent(new Event("change"));
            updateTriggerText();
            closeDropdown();
          });
          optionsList.appendChild(div);
        }
      }
    });

    if (count === 0) {
      optionsList.innerHTML = `<div class="ss-no-results">Data tidak ditemukan.</div>`;
    }
  }

  function updateTriggerText() {
    const selectedOpt = sel.options[sel.selectedIndex];
    if (selectedOpt) {
      textSpan.textContent = selectedOpt.textContent;
    } else {
      textSpan.textContent = "-- Pilih --";
    }
  }

  function openDropdown() {
    document.querySelectorAll(".ss-dropdown.visible").forEach(d => {
      if (d !== dropdown) {
        d.classList.remove("visible");
        d.previousElementSibling?.classList.remove("open");
      }
    });
    dropdown.classList.add("visible");
    trigger.classList.add("open");
    searchInput.value = "";
    buildOptionsUI();
    setTimeout(() => searchInput.focus(), 50);
  }

  function closeDropdown() {
    dropdown.classList.remove("visible");
    trigger.classList.remove("open");
  }

  trigger.addEventListener("click", (e) => {
    e.stopPropagation();
    if (dropdown.classList.contains("visible")) closeDropdown();
    else openDropdown();
  });

  dropdown.addEventListener("click", (e) => {
    e.stopPropagation();
  });

  searchInput.addEventListener("input", () => {
    buildOptionsUI();
  });

  updateTriggerText();

  if (!window._ssDocClickListener) {
    window._ssDocClickListener = true;
    document.addEventListener("click", () => {
      document.querySelectorAll(".ss-dropdown.visible").forEach(d => d.classList.remove("visible"));
      document.querySelectorAll(".ss-trigger.open").forEach(t => t.classList.remove("open"));
    });
  }
}

